"""README.md's measured-results block must match the ledgers it summarizes.

The quality tables in README.md were hand-maintained until August 2026, and
hand maintenance is how a published median stops describing its own ledger.
The block between the ``corpus-results`` markers is now generated by
``tools/update_readme.py``; this test regenerates it and fails on any
difference, so a ledger change that is not reflected in the README -- or a
hand edit inside the generated block -- is a red build, not an inkling.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GENERATOR = REPO / "tools" / "update_readme.py"


def test_readme_corpus_results_block_matches_the_ledgers() -> None:
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"],
        capture_output=True,
        text=True,
        cwd=REPO,
        timeout=120,
    )
    assert result.returncode == 0, (
        f"{result.stdout}{result.stderr}\n"
        "Regenerate with: python tools/update_readme.py"
    )
