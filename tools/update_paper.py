def render_html(report_md: str) -> str:
    content = markdown.markdown(report_md, extensions=["tables"])
    return PAGE_TEMPLATE.format(
        title=TITLE, content=content, version=_version(), url=PAPER_URL
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the report and the Pages HTML match the ledgers",
    )
    args = parser.parse_args()

    try:
        report = render_markdown()
        page = render_html(report)
    except TOOL.LedgerError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    current_md = PAPER_MD.read_text(encoding="utf-8")
    current_html = (
        PAPER_HTML.read_text(encoding="utf-8") if PAPER_HTML.is_file() else ""
    )
    if args.check:
        if current_md != report or current_html != page:
            print(
                "paper is stale: paper/report.md §5.4 or docs/paper/index.html "
                "no longer matches the ledgers. Run "
                "`python tools/update_paper.py`.",
                file=sys.stderr,
            )
            return 1
        print("paper/report.md and docs/paper/index.html are current.")
        return 0

    changed = []
    if current_md != report:
        PAPER_MD.write_text(report, encoding="utf-8")
        changed.append(str(PAPER_MD.relative_to(REPO)))
    PAPER_HTML.parent.mkdir(parents=True, exist_ok=True)
    if current_html != page:
        PAPER_HTML.write_text(page, encoding="utf-8")
        changed.append(str(PAPER_HTML.relative_to(REPO)))
    print("regenerated: " + (", ".join(changed) if changed else "nothing (current)"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
